-- 1. Master Roles
CREATE TABLE IF NOT EXISTS SM_MAS_role (
    MAS_role_id VARCHAR(100) PRIMARY KEY,
    MAS_role_DESC VARCHAR(100),
    MAS_role_LINK VARCHAR(200),
    MAS_role_CREATEDBY VARCHAR(100) references SM_USER_LOGIN(user_id),
    MAS_role_CREATEDAT DATETIME ,
    MAS_role_UPDATEDBY VARCHAR(100) references SM_USER_LOGIN(user_id),
    MAS_role_UPDATEDAT DATETIME 
    );

-- 2. Role Links (New Table)
CREATE TABLE IF NOT EXISTS SM_ROLE_LINKS (
    SM_RL_ID VARCHAR(100) PRIMARY KEY,
    SM_RL_ROLE_ID VARCHAR(100) REFERENCES SM_MAS_role(MAS_role_id),
    SM_RL_LINK_DESC VARCHAR(100),
    SM_RL_LINK_URL VARCHAR(100),
    SM_RL_LINK_SRL INT,
    SM_RL_SUBMENU VARCHAR(100),
    SM_RL_CREATEDBY VARCHAR(100) references SM_USER_LOGIN(user_id),
    SM_RL_CREATEDAT DATETIME ,
    SM_RL_UPDATEDBY VARCHAR(100) references SM_USER_LOGIN(user_id),
    SM_RL_UPDATEDAT DATETIME 
      );

-- 3. User Login
CREATE TABLE IF NOT EXISTS SM_user_login (
    user_id VARCHAR(100) PRIMARY KEY,
    user_email_id VARCHAR(100),
    user_passwd VARCHAR(255),
    user_cr_dt DATE,
    user_role VARCHAR(100) REFERENCES SM_MAS_role(MAS_role_id),
    user_img BLOB,
